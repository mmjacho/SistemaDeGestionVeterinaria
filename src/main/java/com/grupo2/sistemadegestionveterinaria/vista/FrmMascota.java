    private void txtBuscarActionPerformed() {
        // Buscar directamente por c�dula
        try {
            ControladorClienteMascota ctrl = new ControladorClienteMascota();
            List<ModeloMascota> lista = new ArrayList<>();

            // Llamada al método que me acabas de mostrar
            ModeloCliente clienteActual = ctrl.buscar(txtCedula.getText().trim(), lista);

            if (clienteActual != null) {
                mostrarDatosCliente(clienteActual, lista);
            } else {
                limpiarFormulario();
                lbEstado.setText("Nuevo cliente");
            }
        }
        catch (Exception e) {
            abrirModalBusqueda();
        }
    }

    private void limpiarFormulario() {
        // Limpiar campos de texto del cliente
        txtNombre.setText("");
        txtTelefono.setText("");

        // Limpiar tabla de mascotas
        modelo.setRowCount(0);

        // Resetear referencia de cliente actual
        clienteActual = null;

        // Resetear campos de mascota (si los tienes)
        txtMascota.setText("");
        txtRaza.setText("");
    }

    private void abrirModalBusqueda() {
        DlgSeleccionarCliente modal = new DlgSeleccionarCliente(this, true);
        modal.setVisible(true);
        List<ModeloMascota> lista = new ArrayList<>();
        ModeloCliente sel = modal.getClienteSeleccionado();
        if (sel != null) {
            clienteActual = sel;
            txtCedula.setText(sel.getCedula());
            mostrarDatosCliente(clienteActual, lista);
        }
    }

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {
        // 1. Instanciar y abrir el modal como bloqueante (modal = true)
        DlgSeleccionarCliente modal = new DlgSeleccionarCliente(this, true);
        modal.setVisible(true);

        // 2. Al cerrar el modal, recuperamos el cliente seleccionado
        ModeloCliente seleccionado = modal.getClienteSeleccionado();

        if (seleccionado != null) {
            // 3. Si se seleccionó uno, cargamos sus datos y sus mascotas
            cargarDatosDesdeCliente(seleccionado);
        } else {
            // 4. Si el usuario cerró el modal sin seleccionar nada (o canceló)
            // Puedes decidir si limpiar o no hacer nada
            lbEstado.setText("Búsqueda cancelada");
        }
    }

    private void cargarDatosDesdeCliente(ModeloCliente c) {
        try {
            ControladorClienteMascota ctrl = new ControladorClienteMascota();
            List<ModeloMascota> lista = new ArrayList<>();

            // Obtenemos los datos completos (cliente + mascotas)
            this.clienteActual = ctrl.buscar(c.getCedula(), lista);

            // Actualizamos la vista
            txtCedula.setText(clienteActual.getCedula());
            txtNombre.setText(clienteActual.getNombres());
            txtTelefono.setText(clienteActual.getTelefono());

            modelo.setRowCount(0);
            for (ModeloMascota m : lista) {
                modelo.addRow(new Object[]{m.getId(), m.getNombre(), m.getRaza(), m.getEspecie()});
            }
            lbEstado.setText("Cliente cargado: " + clienteActual.getNombres());

        }
        catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar datos: " + e.getMessage());
        }
    }
  private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed

        if (txtMascota.getText().isEmpty() || txtRaza.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete datos mascota");
            return;
        }

        modelo.addRow(new Object[]{
            0,
            txtMascota.getText(),
            txtRaza.getText(),
            cbEspecie.getSelectedItem().toString()
        });

        txtMascota.setText("");
        txtRaza.setText("");
  }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnRepoActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            List<String[]> datos = dao.obtenerReporteCompleto();
            java.io.File archivo = new java.io.File("Reporte_Clientes_Mascotas.txt");
            java.io.PrintWriter writer = new java.io.PrintWriter(archivo);

            writer.println("REPORTE DE CLIENTES Y MASCOTAS");
            writer.println("===============================");
            writer.printf("%-15s %-20s %-20s %-15s%n", "Cédula", "Cliente", "Mascota", "Especie");
            writer.println("---------------------------------------------------------------");

            for (String[] fila : datos) {
                writer.printf("%-15s %-20s %-20s %-15s%n",
                        fila[0], fila[1],
                        (fila[2] == null ? "Sin mascota" : fila[2]),
                        (fila[3] == null ? "-" : fila[3]));
            }

            writer.close();
            JOptionPane.showMessageDialog(this, "Reporte generado con éxito en: " + archivo.getAbsolutePath());

            // Opcional: Abrir el archivo automáticamente
            if (Desktop.isDesktopSupported()) {
                Desktop.getDesktop().open(archivo);
            }
        }
        catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al generar reporte: " + e.getMessage());
        }
    }

